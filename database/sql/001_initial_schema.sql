-- 18. Views para estatisticas. security_invoker respeita RLS das tabelas.
create or replace view public.v_inventory_summary
with (security_invoker = true)
as
select
  l.user_id,
  l.cellar_id,
  c.name as cellar_name,
  count(distinct l.wine_id) as wine_count,
  coalesce(sum(l.quantity), 0)::bigint as bottle_count,
  coalesce(sum(l.quantity * l.unit_cost), 0)::numeric(14,2) as inventory_cost,
  case when sum(l.quantity) > 0
    then (sum(l.quantity * l.unit_cost) / sum(l.quantity))::numeric(12,2)
    else 0::numeric
  end as average_unit_cost
from public.inventory_lots l
join public.cellars c on c.id = l.cellar_id
group by l.user_id, l.cellar_id, c.name;

create or replace view public.v_inventory_by_country
with (security_invoker = true)
as
select
  l.user_id,
  l.cellar_id,
  w.country_id,
  coalesce(ct.name, 'País não informado') as country_name,
  ct.iso2 as country_iso2,
  ct.flag_emoji,
  coalesce(sum(l.quantity), 0)::bigint as bottle_count,
  coalesce(sum(l.quantity * l.unit_cost), 0)::numeric(14,2) as inventory_cost
from public.inventory_lots l
join public.wines w on w.id = l.wine_id
left join public.countries ct on ct.id = w.country_id
group by l.user_id, l.cellar_id, w.country_id, ct.name, ct.iso2, ct.flag_emoji;

grant select on public.v_inventory_summary, public.v_inventory_by_country to authenticated;

